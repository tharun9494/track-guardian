import { Download, FileText } from "lucide-react";
import jsPDF from "jspdf";

interface CrackEvent {
  id: string;
  vibration: number;
  dateTime: string;
  status: string;
  timestamp: number;
}

interface PDFReportGeneratorProps {
  maxVibration: number;
  crackEvents: CrackEvent[];
  currentDate: Date;
}

const PDFReportGenerator = ({ maxVibration, crackEvents, currentDate }: PDFReportGeneratorProps) => {
  const generatePDF = () => {
    const doc = new jsPDF();
    
    // Set font to support more characters (you might need to add a font that supports your characters)
    doc.setFont("helvetica");
    
    // Title
    doc.setFontSize(20);
    doc.text("Railway Vibration Monitoring Report", 20, 20);
    
    // Date
    doc.setFontSize(12);
    doc.text(`Report Date: ${currentDate.toLocaleDateString()}`, 20, 35);
    doc.text(`Report Time: ${currentDate.toLocaleTimeString()}`, 20, 45);
    
    // Summary Section
    doc.setFontSize(14);
    doc.text("Summary", 20, 65);
    
    doc.setFontSize(11);
    doc.text(`Maximum Vibration Recorded: ${maxVibration}`, 20, 80);
    doc.text(`Total Crack Events: ${crackEvents.length}`, 20, 90);
    
    // Events Table Header
    if (crackEvents.length > 0) {
      doc.setFontSize(14);
      doc.text("Crack Events Details", 20, 110);
      
      doc.setFontSize(10);
      let yPos = 125;
      
      // Table headers
      doc.text("Date & Time", 20, yPos);
      doc.text("Vibration", 80, yPos);
      doc.text("Status", 130, yPos);
      
      yPos += 10;
      
      // Table rows (show first 10 events to fit on page)
      const eventsToShow = crackEvents.slice(0, 10);
      eventsToShow.forEach((event) => {
        if (yPos > 270) {
          doc.addPage();
          yPos = 20;
        }
        
        doc.text(event.dateTime, 20, yPos);
        doc.text(event.vibration.toString(), 80, yPos);
        doc.text(event.status, 130, yPos);
        yPos += 8;
      });
      
      if (crackEvents.length > 10) {
        doc.text(`... and ${crackEvents.length - 10} more events`, 20, yPos + 5);
      }
    } else {
      doc.setFontSize(11);
      doc.text("No crack events detected during this monitoring period.", 20, 110);
    }
    
    // Footer
    doc.setFontSize(10);
    doc.text("Generated by AI Railway Structural Monitoring System", 20, 280);
    doc.text("Powered by ESP32 + Firebase", 20, 285);
    
    // Save the PDF
    doc.save(`vibration-report-${currentDate.getTime()}.pdf`);
  };

  return (
    <div className="rounded-xl border border-border bg-card p-6">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="text-sm font-medium uppercase tracking-widest text-muted-foreground">
            Report Generator
          </h3>
          <p className="text-xs text-muted-foreground/60 mt-1">
            Download monitoring report as PDF
          </p>
        </div>
        
        <button
          onClick={generatePDF}
          className="flex items-center gap-2 px-4 py-2 bg-primary text-primary-foreground rounded-lg hover:bg-primary/90 transition-colors text-sm font-medium"
        >
          <Download className="h-4 w-4" />
          Download Report
        </button>
      </div>
      
      <div className="mt-4 grid grid-cols-1 sm:grid-cols-3 gap-4">
        <div className="text-center p-3 rounded-lg bg-muted/50">
          <FileText className="h-6 w-6 mx-auto mb-1 text-muted-foreground" />
          <p className="text-xs text-muted-foreground">PDF Format</p>
        </div>
        <div className="text-center p-3 rounded-lg bg-muted/50">
          <span className="text-lg font-bold text-primary">{maxVibration}</span>
          <p className="text-xs text-muted-foreground">Max Vibration</p>
        </div>
        <div className="text-center p-3 rounded-lg bg-muted/50">
          <span className="text-lg font-bold text-danger">{crackEvents.length}</span>
          <p className="text-xs text-muted-foreground">Crack Events</p>
        </div>
      </div>
    </div>
  );
};

export default PDFReportGenerator;
